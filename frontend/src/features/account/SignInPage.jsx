/**
 * Sign-in.
 *
 * Deployed, this page starts an OAuth 2.0 Authorization Code flow with PKCE
 * against the Cognito user pool (see auth/cognito.js). The browser never holds
 * a client secret, and the access token is verified by the API against the
 * pool's published keys.
 *
 * What this page used to do, and why it was wrong: it displayed a panel headed
 * "Local development sign-in", instructed visitors to run
 * `python scripts/dev.py token user-donor-1`, and listed every seeded account
 * id with its role — including the platform administrator and the hospital
 * authorizer. On a public URL that is an invitation and a disclosure, not a
 * convenience. The development path now exists only in a development build:
 * `import.meta.env.DEV` is a compile-time constant, so the block below is
 * removed from the production bundle rather than merely hidden at runtime.
 */
import { useState } from 'react'
import { Link, Navigate, useLocation } from 'react-router-dom'

import { useAuth } from '../../auth/AuthContext.jsx'
import { beginSignIn, isCognitoConfigured } from '../../auth/cognito.js'
import { safeInternalPath } from '../../auth/redirect.js'
import { Button, Card, Field, Notice } from '../../components/ui.jsx'

export function SignInPage() {
  const { isAuthenticated, signInWithToken, error, status, devSignInEnabled } = useAuth()
  const location = useLocation()
  const [token, setToken] = useState('')
  const [redirecting, setRedirecting] = useState(false)
  const [startError, setStartError] = useState(null)

  if (isAuthenticated) {
    // Validated, never used raw: `from` originates in a pathname an attacker
    // can shape (`//evil.com`), and handing that to Navigate is an open
    // redirect off a sign-in page. See auth/redirect.js.
    return <Navigate to={safeInternalPath(location.state?.from)} replace />
  }

  const cognitoReady = isCognitoConfigured()
  const returnTo = safeInternalPath(location.state?.from)

  const startCognito = async () => {
    setStartError(null)
    setRedirecting(true)
    try {
      await beginSignIn({ returnTo })
    } catch (cause) {
      setRedirecting(false)
      setStartError(cause?.message ?? 'Sign-in could not be started.')
    }
  }

  return (
    <div className="stack stack--narrow">
      <header className="page-header">
        <h1>Sign in</h1>
        <p className="page-header__lead">
          Staff and donor accounts sign in through the LifeLink identity
          provider. Browsing blood availability does not require an account.
        </p>
      </header>

      <nav className="auth-tabs" aria-label="Account">
        <span className="auth-tabs__tab auth-tabs__tab--active" aria-current="page">
          Sign in
        </span>
        <Link to="/sign-up" className="auth-tabs__tab">Create account</Link>
      </nav>

      <Card title="Sign in to LifeLink">
        {cognitoReady ? (
          <>
            <p className="text-sm">
              You will be taken to a secure sign-in page and returned here
              afterwards.
            </p>
            <Button type="button" onClick={startCognito} disabled={redirecting}>
              {redirecting ? 'Redirecting…' : 'Continue to secure sign-in'}
            </Button>
            {startError ? (
              <p className="field__error" role="alert">{startError}</p>
            ) : null}
          </>
        ) : (
          <Notice tone="warning" title="Sign-in is not available">
            <p className="text-sm" style={{ margin: 0 }}>
              This build has no identity provider configured, so accounts cannot
              sign in. Public pages — blood availability, facilities and donation
              camps — are unaffected.
            </p>
          </Notice>
        )}
      </Card>

      {status === 'error' && error ? (
        <Notice tone="warning" title="Sign-in problem">
          <p className="text-sm" style={{ margin: 0 }}>{error}</p>
        </Notice>
      ) : null}

      {/*
        Development-only. `import.meta.env.DEV` is replaced at build time, so
        this whole branch is eliminated from the production bundle; it is not
        merely hidden behind a flag a user could flip.
      */}
      {devSignInEnabled ? (
        <Card
          title="Development sign-in"
          subtitle="Local builds only — not present in the deployed bundle"
        >
          <form
            onSubmit={(event) => {
              event.preventDefault()
              signInWithToken(token)
            }}
          >
            <Field
              label="Paste a development token"
              htmlFor="token"
              hint="Generated by the project's local development helper."
              error={status === 'error' ? error : null}
            >
              {({ id, describedBy }) => (
                <textarea
                  id={id}
                  aria-describedby={describedBy}
                  rows={4}
                  value={token}
                  onChange={(event) => setToken(event.target.value)}
                  spellCheck="false"
                />
              )}
            </Field>
            <Button type="submit" variant="secondary" disabled={!token.trim()}>
              Sign in with token
            </Button>
          </form>
        </Card>
      ) : null}
    </div>
  )
}
